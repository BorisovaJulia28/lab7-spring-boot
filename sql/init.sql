CREATE TABLE IF NOT EXISTS STUDENTS (
                                        id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        name VARCHAR(15),
    surname VARCHAR(25),
    faculty VARCHAR(20),
    age INT
    );

CREATE TABLE IF NOT EXISTS STUDY_GROUPS (
                                            id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                            name VARCHAR(20),
    faculty VARCHAR(20),
    course INT
    );